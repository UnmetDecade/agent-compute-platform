/**
 * Chinese/English UI: the browser language picks the initial language, and a saved choice wins.
 *
 * English is the source language and the dictionary key: t("Builders") looks up the Chinese
 * translation in ZH. Missing translations fall back to English, so an untranslated addition
 * never becomes blank. Switching language remounts the whole subtree via a Fragment key, so
 * every render-time t() in components recomputes in the new language.
 */
export type Lang = "zh" | "en";

const STORAGE_KEY = "app-lang";
/** Marks a choice the user made in the language switch; old auto-saved values lack it. */
const EXPLICIT_KEY = "app-lang-explicit";

/**
 * The browser language decides the first render: any Chinese variant uses Chinese,
 * anything else (including a missing navigator in SSR/tests) uses English.
 * A user's saved choice always wins over the browser default.
 */
export function detectLang(nav?: Pick<Navigator, "language" | "languages">): Lang {
  const source = nav ?? (typeof navigator === "undefined" ? undefined : navigator);
  if (!source) return "en";
  const candidates = [source.language, ...(source.languages ?? [])].filter(Boolean);
  return candidates.some((value) => value.toLowerCase().startsWith("zh")) ? "zh" : "en";
}

/**
 * A saved choice is honored only when it came from the language switch. Older
 * builds could auto-save the detected language, which froze the UI in whatever
 * the first visit happened to be; those values are ignored so the browser
 * language keeps deciding the default.
 */
export function storedLang(): Lang {
  try {
    const explicit = localStorage.getItem(EXPLICIT_KEY) === "1";
    const saved = localStorage.getItem(STORAGE_KEY);
    if (explicit && (saved === "en" || saved === "zh")) return saved;
  } catch {
    // localStorage can be unavailable in private mode; fall back to the browser language.
  }
  return detectLang();
}

