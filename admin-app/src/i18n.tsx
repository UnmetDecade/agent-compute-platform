/** Translate an English source string into the current language; supports {name} placeholders. */
export function t(en: string, vars?: Record<string, string | number>): string {
  let out = current === "zh" ? ZH[en] ?? en : en;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      out = out.split(`{${key}}`).join(String(value));
    }
  }
  return out;
}

export function currentLang(): Lang {
  return current;
}

const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({
  lang: current,
  setLang: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(storedLang);
  // Sync the module variable during render so the subtree rendered right after sees the new language.
  current = lang;

  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);

  const setLang = (next: Lang) => {
    current = next;
    setLangState(next);
    // Persist only an explicit choice; the initial language keeps following the browser.
    try {
      localStorage.setItem(STORAGE_KEY, next);
      localStorage.setItem(EXPLICIT_KEY, "1");
    } catch {
      // localStorage cannot be written in private mode; the change still applies to this session.
    }
  };

  return (
    <LangContext.Provider value={{ lang, setLang }}>
      <Fragment key={lang}>{children}</Fragment>
    </LangContext.Provider>
  );
}

export function useI18n() {
  return useContext(LangContext);
}
